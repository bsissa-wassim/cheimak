export function setLanguage(locale) {
  if (!Object.hasOwn(translations, locale)) return false;
  const dictionary = translations[locale];

  for (const element of document.querySelectorAll('[data-i18n]')) {
    const text = dictionary[element.dataset.i18n];
    if (text !== undefined) element.textContent = text;
  }

  for (const [hook, attribute] of [
    ['data-i18n-aria-label', 'aria-label'],
    ['data-i18n-alt', 'alt'],
    ['data-i18n-content', 'content'],
  ]) {
    for (const element of document.querySelectorAll(`[${hook}]`)) {
      const text = dictionary[element.getAttribute(hook)];
      if (text !== undefined) element.setAttribute(attribute, text);
    }
  }

  document.documentElement.lang = locale;
  document.title = document.body?.dataset.page === 'senior' ? dictionary.seniorPageTitle : dictionary.pageTitle;
  for (const link of document.querySelectorAll('[data-universe-link]')) {
    const [path, hash] = link.dataset.universeLink.split('#');
    link.setAttribute('href', `${path}?lang=${locale}${hash ? `#${hash}` : ''}`);
  }
  for (const button of document.querySelectorAll('[data-locale]')) {
    button.setAttribute('aria-pressed', String(button.dataset.locale === locale));
  }
  document.dispatchEvent(new CustomEvent('glowlink:languagechange', { detail: { locale } }));
  return true;
}

export function initLanguage() {
  const group = document.querySelector('[data-language-switch]');
  if (!group) return;

  group.addEventListener('click', (event) => {
    const button = event.target.closest?.('[data-locale]');
    if (button && group.contains(button)) setLanguage(button.dataset.locale);
  });
  const requested = new URLSearchParams(window.location.search).get('lang');
  if (requested) setLanguage(requested);
}
